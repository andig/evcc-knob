"""Convert Montserrat TTFs to anti-aliased VLW fonts in src/fonts.h.

Usage: uv run --with pillow python tools/mkfonts.py <dir with Montserrat-*.ttf>
Fonts: https://github.com/JulietaUla/Montserrat (SIL Open Font License)
"""
import struct
import sys
from pathlib import Path

from PIL import ImageFont

TEXT = "".join(chr(c) for c in range(0x21, 0x7F)) + "°·"
DIGITS = "0123456789.:-%"
# name, weight, pixel size, characters; sizes are the design sizes halved
FONTS = [
    ("SMALL", "Medium", 11, TEXT),
    ("MED", "SemiBold", 13, TEXT),
    ("UNIT", "SemiBold", 15, TEXT),
    ("LARGE", "Bold", 30, TEXT),
    ("NUM36", "Bold", 36, DIGITS),
    ("NUM48", "Bold", 48, DIGITS),
    ("NUM52", "Bold", 52, DIGITS),
    ("NUM60", "Bold", 60, DIGITS),
]


def vlw(path, size, chars):
    font = ImageFont.truetype(str(path), size)
    glyphs, bitmaps = b"", b""
    for ch in sorted(chars):
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        mask = font.getmask(ch, mode="L")
        w, h = mask.size
        assert (w, h) == (right - left, bottom - top), ch
        # unicode, height, width, xAdvance, top above baseline, left offset, unused
        glyphs += struct.pack(">7i", ord(ch), h, w, round(font.getlength(ch)), -top, left, 0)
        bitmaps += bytes(mask)
    ascent = -font.getbbox("d", anchor="ls")[1]
    descent = font.getbbox("p", anchor="ls")[3]
    return struct.pack(">6i", len(chars), 11, size, 0, ascent, descent) + glyphs + bitmaps


src = Path(sys.argv[1])
out = [
    "// Montserrat as VLW fonts. Generated by tools/mkfonts.py, do not edit.",
    "// Montserrat is licensed under the SIL Open Font License, see tools/Montserrat-OFL.txt",
    "#pragma once",
    "#include <stdint.h>",
    "",
]
for name, weight, size, chars in FONTS:
    data = vlw(src / f"Montserrat-{weight}.ttf", size, chars)
    rows = [", ".join(str(b) for b in data[i : i + 32]) for i in range(0, len(data), 32)]
    out.append(f"static const uint8_t FONT_{name}[] = {{\n" + ",\n".join(rows) + "};")
    print(name, len(data), "bytes")
(Path(__file__).parent.parent / "src" / "fonts.h").write_text("\n".join(out) + "\n")
